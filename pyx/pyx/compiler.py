"""PyX compiler frontend: custom syntax -> Python AST -> CPython code object."""
import ast
import io
import re
import tokenize
from dataclasses import dataclass

class PyXError(Exception):
    pass

@dataclass
class CompileResult:
    python_source: str
    code: object

def _split_pipeline(expr):
    """Split top-level |> operators, respecting strings and brackets."""
    parts, start, depth = [], 0, 0
    quote = None
    i = 0
    while i < len(expr):
        c = expr[i]
        if quote:
            if c == "\\\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in ("'", '"'):
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif expr.startswith("|>", i) and depth == 0:
            parts.append(expr[start:i].strip())
            start = i + 2
            i += 1
        i += 1
    if parts:
        parts.append(expr[start:].strip())
        return parts
    return None

def _pipeline_to_python(expr, line_no):
    parts = _split_pipeline(expr)
    if not parts:
        return expr
    if any(not p for p in parts):
        raise PyXError(f"Line {line_no}: incomplete pipeline")
    try:
        current = ast.parse(parts[0], mode="eval").body
        for stage in parts[1:]:
            node = ast.parse(stage, mode="eval").body
            if isinstance(node, ast.Name):
                current = ast.Call(func=node, args=[current], keywords=[])
            elif isinstance(node, ast.Call):
                node.args.insert(0, current)
                current = node
            else:
                raise PyXError(f"Line {line_no}: pipeline stage must be a function name or call")
        return ast.unparse(current)
    except SyntaxError as exc:
        raise PyXError(f"Line {line_no}: invalid pipeline expression: {exc.msg}") from exc

def compile_source(source, filename="<pyx>"):
    """Compile PyX source into a CPython code object."""
    if not isinstance(source, str):
        raise TypeError("source must be a string")
    output = ["# Generated by the PyX compiler"]
    strict = False
    for number, original in enumerate(source.splitlines(), 1):
        stripped = original.strip()
        if not stripped or stripped.startswith("#"):
            output.append(original)
            continue
        indent = original[:len(original)-len(original.lstrip())]
        line = stripped

        if line == "strict on":
            strict = True
            output.append(indent + "__pyx_strict__ = True")
            continue
        if line == "strict off":
            strict = False
            output.append(indent + "__pyx_strict__ = False")
            continue

        # Custom function and control-flow keywords.
        if line.startswith("fn "):
            line = "def " + line[3:]
        elif line.startswith("when "):
            line = "if " + line[5:]
        elif line == "otherwise:":
            line = "else:"
        elif line.startswith("otherwise when "):
            line = "elif " + line[len("otherwise when "):]
        elif line.startswith("give "):
            line = "return " + line[5:]

        # let name[: type] = expression
        let_match = re.match(r"let\s+([A-Za-z_]\w*)(?:\s*:\s*([A-Za-z_]\w*))?\s*=\s*(.+)$", line)
        if let_match:
            name, type_name, expression = let_match.groups()
            expression = _pipeline_to_python(expression, number)
            output.append(indent + f"{name} = {expression}")
            if type_name:
                if type_name not in {"int", "float", "str", "bool", "list", "dict", "tuple", "set"}:
                    raise PyXError(f"Line {number}: unsupported strict type '{type_name}'")
                output.append(indent + f"__pyx_check_type({name!r}, {name}, {type_name})")
            continue

        # Pipelines can appear in ordinary assignments, returns, and expressions.
        # Only rewrite the expression portion, not strings/comments.
        comment_split = line.split("#", 1)
        code_part = comment_split[0].rstrip()
        comment = (" #" + comment_split[1]) if len(comment_split) == 2 else ""
        if "|>" in code_part:
            if "=" in code_part:
                left, right = code_part.split("=", 1)
                code_part = left + "= " + _pipeline_to_python(right.strip(), number)
            elif code_part.startswith("return "):
                code_part = "return " + _pipeline_to_python(code_part[7:].strip(), number)
            else:
                code_part = _pipeline_to_python(code_part, number)
        output.append(indent + code_part + comment)

    python_source = "\n".join(output) + "\n"
    # Tokenization catches malformed lexical input before the CPython parser.
    try:
        list(tokenize.generate_tokens(io.StringIO(python_source).readline))
        tree = ast.parse(python_source, filename=filename)
    except (tokenize.TokenError, IndentationError, SyntaxError) as exc:
        msg = getattr(exc, "msg", str(exc))
        line = getattr(exc, "lineno", None)
        where = f" at line {line}" if line else ""
        raise PyXError(f"PyX syntax error{where}: {msg}") from exc
    ast.fix_missing_locations(tree)
    code = compile(tree, filename, "exec")
    return CompileResult(python_source, code)

def check_type(name, value, expected):
    if not isinstance(value, expected):
        raise TypeError(
            f"PyX strict type error: '{name}' expected {expected.__name__}, "
            f"got {type(value).__name__}"
        )
    return value

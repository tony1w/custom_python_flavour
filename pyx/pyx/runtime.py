"""Runtime helpers and command-line interface for PyX."""
import argparse
import code
import pathlib
import sys
from .compiler import compile_source, check_type, PyXError

def _namespace():
    return {
        "__name__": "__main__",
        "__pyx_check_type": check_type,
        "__pyx_strict__": False,
    }

def run_source(source, filename="<pyx>", debug=False, namespace=None):
    result = compile_source(source, filename)
    if debug:
        print("----- CPython source generated by PyX -----")
        print(result.python_source)
        print("-------------------------------------------")
    env = _namespace()
    if namespace:
        env.update(namespace)
    exec(result.code, env, env)
    return env

def run_file(path, debug=False):
    path = pathlib.Path(path)
    try:
        source = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PyXError(f"cannot read {path}: {exc}") from exc
    return run_source(source, str(path), debug)

def repl():
    print("PyX interactive shell (CPython backend). Type :quit to exit, :debug to toggle debug.")
    debug = False
    env = _namespace()
    buffer = []
    while True:
        try:
            prompt = "... " if buffer else "pyx> "
            line = input(prompt)
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not buffer and line.strip() == ":quit":
            break
        if not buffer and line.strip() == ":debug":
            debug = not debug
            print("Debug:", "on" if debug else "off")
            continue
        if not line.strip() and not buffer:
            continue
        buffer.append(line)
        # Blank line ends a block, like the standard Python REPL.
        if line.strip():
            continue
        source = "\n".join(buffer)
        buffer.clear()
        try:
            run_source(source, "<repl>", debug, env)
        except Exception as exc:
            print(f"{type(exc).__name__}: {exc}")
    print("Leaving PyX.")

def main(argv=None):
    parser = argparse.ArgumentParser(prog="pyx", description="PyX custom Python flavour")
    parser.add_argument("file", nargs="?", help="Path to a .pyx source file")
    parser.add_argument("--debug", action="store_true", help="show generated Python source")
    parser.add_argument("--version", action="version", version="PyX 1.0.0")
    args = parser.parse_args(argv)
    if not args.file:
        repl()
        return 0
    try:
        run_file(args.file, args.debug)
        return 0
    except (PyXError, Exception) as exc:
        print(f"PyX error: {exc}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    raise SystemExit(main())
